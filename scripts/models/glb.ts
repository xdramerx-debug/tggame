import { GLTFExporter } from 'three/examples/jsm/exporters/GLTFExporter.js';
import type { AnimationClip, Object3D } from 'three';

/**
 * GLB export for the asset pipeline.
 *
 * `GLTFExporter` reads its binary output back through `FileReader`, which Node
 * does not have. The shim below implements only the two calls the exporter makes
 * (`readAsArrayBuffer` + `onloadend`) on top of `Blob.arrayBuffer()`, so the
 * exporter runs headless with no browser and no extra dependencies.
 */
class NodeFileReader {
  result: ArrayBuffer | string | null = null;
  onloadend: (() => void) | null = null;
  onerror: ((error: unknown) => void) | null = null;

  readAsArrayBuffer(blob: Blob): void {
    blob
      .arrayBuffer()
      .then((buffer) => {
        this.result = buffer;
        this.onloadend?.();
      })
      .catch((error: unknown) => this.onerror?.(error));
  }

  readAsDataURL(blob: Blob): void {
    blob
      .arrayBuffer()
      .then((buffer) => {
        const base64 = Buffer.from(buffer).toString('base64');
        this.result = `data:${blob.type || 'application/octet-stream'};base64,${base64}`;
        this.onloadend?.();
      })
      .catch((error: unknown) => this.onerror?.(error));
  }
}

let shimInstalled = false;

/** Installs the `FileReader` shim once per process. */
export function installNodeExportShim(): void {
  if (shimInstalled) return;
  const scope = globalThis as unknown as { FileReader?: unknown };
  if (typeof scope.FileReader === 'undefined') scope.FileReader = NodeFileReader;
  shimInstalled = true;
}

export interface ExportOptions {
  readonly animations?: readonly AnimationClip[];
  readonly copyright?: string;
}

/**
 * Serialises an object tree into a self-contained GLB buffer.
 * `binary: true` is used everywhere so the result is a single file, which keeps
 * the asset manifest trivial (`<name>.glb` and nothing else).
 */
export async function exportGlb(root: Object3D, options: ExportOptions = {}): Promise<ArrayBuffer> {
  installNodeExportShim();
  const exporter = new GLTFExporter();
  const result = await exporter.parseAsync(root, {
    binary: true,
    // The exporter indexes `options.animations` unconditionally, so always pass an array.
    animations: options.animations ? [...options.animations] : [],
    copyright: options.copyright ?? 'TENEBRIS — procedural asset, generated by scripts/build-assets.ts',
    onlyVisible: false,
  });
  if (!(result instanceof ArrayBuffer)) {
    throw new Error('GLTFExporter returned a JSON document; binary export failed');
  }
  return result;
}

/** Parsed view of a GLB container, used by the asset tests. */
export interface GlbInfo {
  readonly magic: number;
  readonly version: number;
  readonly totalLength: number;
  readonly json: {
    readonly asset?: { readonly version?: string; readonly generator?: string };
    readonly meshes?: readonly {
      readonly name?: string;
      readonly primitives: readonly { readonly attributes: Record<string, number> }[];
    }[];
    readonly nodes?: readonly { readonly name?: string; readonly skin?: number; readonly mesh?: number }[];
    readonly skins?: readonly { readonly joints: readonly number[]; readonly skeleton?: number }[];
    readonly animations?: readonly {
      readonly name?: string;
      readonly channels: readonly unknown[];
      readonly samplers: readonly unknown[];
    }[];
    readonly materials?: readonly { readonly name?: string }[];
    readonly accessors?: readonly { readonly count: number; readonly type: string }[];
  };
  readonly binaryLength: number;
}

const GLB_MAGIC = 0x46546c67;

/** Parses the GLB header and JSON chunk (no three.js involved). */
export function inspectGlb(buffer: ArrayBuffer): GlbInfo {
  const view = new DataView(buffer);
  const magic = view.getUint32(0, true);
  if (magic !== GLB_MAGIC) throw new Error(`not a GLB file (magic 0x${magic.toString(16)})`);
  const version = view.getUint32(4, true);
  const totalLength = view.getUint32(8, true);
  const jsonLength = view.getUint32(12, true);
  const jsonType = view.getUint32(16, true);
  if (jsonType !== 0x4e4f534a) throw new Error('first GLB chunk is not JSON');
  const jsonText = new TextDecoder().decode(new Uint8Array(buffer, 20, jsonLength));
  const json = JSON.parse(jsonText) as GlbInfo['json'];
  const binaryHeaderOffset = 20 + jsonLength;
  const binaryLength =
    binaryHeaderOffset + 8 <= buffer.byteLength ? view.getUint32(binaryHeaderOffset, true) : 0;
  return { magic, version, totalLength, json, binaryLength };
}
