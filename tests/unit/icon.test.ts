import { describe, expect, it } from 'vitest';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { inflateSync } from 'node:zlib';
import { buildIcons, encodePng, renderIcon } from '../../scripts/icon';

const PUBLIC = join(process.cwd(), 'public', 'assets');

/** Minimal PNG reader: enough to prove size, colour type and pixel payload. */
function inspectPng(bytes: Buffer): { width: number; height: number; bitDepth: number; colourType: number; data: Buffer } {
  const signature = bytes.subarray(0, 8);
  expect([...signature]).toEqual([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  const ihdrLength = bytes.readUInt32BE(8);
  expect(bytes.subarray(12, 16).toString('ascii')).toBe('IHDR');
  const width = bytes.readUInt32BE(16);
  const height = bytes.readUInt32BE(20);
  const bitDepth = bytes[24] ?? 0;
  const colourType = bytes[25] ?? 0;
  expect(ihdrLength).toBe(13);

  // Concatenate every IDAT chunk, then inflate.
  let offset = 8;
  const chunks: Buffer[] = [];
  while (offset < bytes.length) {
    const length = bytes.readUInt32BE(offset);
    const type = bytes.subarray(offset + 4, offset + 8).toString('ascii');
    const data = bytes.subarray(offset + 8, offset + 8 + length);
    if (type === 'IDAT') chunks.push(Buffer.from(data));
    offset += 12 + length;
    if (type === 'IEND') break;
  }
  return { width, height, bitDepth, colourType, data: inflateSync(Buffer.concat(chunks)) };
}

/**
 * The icon is an asset like any other: generated by code, verified by code.
 * A silently corrupt PNG is only discovered when Telegram or iOS refuses to
 * install the app, which is exactly the wrong moment.
 */
describe('app icon', () => {
  it('writes a true-colour PNG with the requested dimensions', () => {
    const [icon] = buildIcons();
    if (!icon) throw new Error('no icons generated');
    const png = inspectPng(icon.bytes);
    expect(png.width).toBe(192);
    expect(png.height).toBe(192);
    expect(png.bitDepth).toBe(8);
    expect(png.colourType).toBe(6);
    // Every scanline carries a filter byte + 4 channels per pixel.
    expect(png.data.length).toBe((192 * 4 + 1) * 192);
  });

  it('renders a fully opaque icon (no transparency surprises on the app grid)', () => {
    const pixels = renderIcon({ size: 32 });
    for (let i = 3; i < pixels.length; i += 4) expect(pixels[i]).toBe(255);
  });

  it('draws the ember brighter than the stone it sits in', () => {
    const size = 64;
    const pixels = renderIcon({ size });
    const lum = (x: number, y: number): number => {
      const offset = (y * size + x) * 4;
      return (pixels[offset] ?? 0) + (pixels[offset + 1] ?? 0) + (pixels[offset + 2] ?? 0);
    };
    const centre = Math.floor(size / 2);
    // Ember sits slightly below the middle of the arch.
    const ember = lum(centre, Math.round(size * 0.58));
    const corner = lum(2, 2);
    expect(ember).toBeGreaterThan(corner * 2);
  });

  it('shrinks the mark inside the maskable safe zone', () => {
    const normal = renderIcon({ size: 48 });
    const maskable = renderIcon({ size: 48, maskable: true });
    const edgeLum = (pixels: Uint8Array): number => {
      let sum = 0;
      for (let x = 0; x < 48; x += 1) {
        const offset = ((0 * 48) + x) * 4;
        sum += (pixels[offset] ?? 0) + (pixels[offset + 1] ?? 0) + (pixels[offset + 2] ?? 0);
      }
      return sum;
    };
    // The top edge of the maskable variant is bare background.
    expect(edgeLum(maskable)).toBeLessThanOrEqual(edgeLum(normal));
  });

  it('is deterministic and matches the files written by the pipeline', () => {
    const first = encodePng(renderIcon({ size: 64 }), 64);
    const second = encodePng(renderIcon({ size: 64 }), 64);
    expect(Buffer.compare(first, second)).toBe(0);

    for (const artifact of buildIcons()) {
      const path = join(PUBLIC, artifact.file);
      if (!existsSync(path)) continue; // assets are generated, not committed
      expect(readFileSync(path).byteLength).toBe(artifact.bytes.byteLength);
    }
  });
});
