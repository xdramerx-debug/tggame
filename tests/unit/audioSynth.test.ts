import { describe, expect, it } from 'vitest';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { SOUNDS, renderSound, totalAudioBytes } from '../../scripts/audio/sfx';
import { decodeWav, encodeWav, SAMPLE_RATE } from '../../scripts/audio/wav';
import { SOUND_IDS, SOUND_SPECS } from '@/game/audio/soundSet';

const PUBLIC = join(process.cwd(), 'public', 'assets');
const MANIFEST = JSON.parse(readFileSync(join(PUBLIC, 'manifest.json'), 'utf8')) as {
  version: number;
  sampleRate: number;
  audio: { id: string; file: string; bytes: number; durationSec: number; category: string; peak: number }[];
};

/**
 * Audio is generated by code, so the generator is tested like code: the same
 * build function the pipeline calls runs here, and the bytes are inspected —
 * clipping, DC offset and a non-zero tail are the three things that make a
 * procedurally synthesised cue sound broken on a phone speaker.
 */
describe('procedural audio', () => {
  it('renders every sound with a valid RIFF header and mono 22.05 kHz 16-bit PCM', () => {
    expect(SOUNDS.length).toBeGreaterThanOrEqual(19);
    for (const sound of SOUNDS) {
      const bytes = encodeWav(renderSound(sound));
      const { info } = decodeWav(bytes);
      expect(info.sampleRate).toBe(SAMPLE_RATE);
      expect(info.channels).toBe(1);
      expect(info.bitsPerSample).toBe(16);
      expect(info.durationSec).toBeCloseTo(sound.durationSec, 1);
      expect(String.fromCharCode(...bytes.slice(0, 4))).toBe('RIFF');
      expect(String.fromCharCode(...bytes.slice(8, 12))).toBe('WAVE');
    }
  });

  it('is deterministic: two renders are byte-identical', () => {
    for (const sound of SOUNDS) {
      const a = encodeWav(renderSound(sound));
      const b = encodeWav(renderSound(sound));
      expect(Buffer.compare(Buffer.from(a), Buffer.from(b))).toBe(0);
    }
  });

  it('stays inside the peak budget, without clipping or a DC offset', () => {
    for (const sound of SOUNDS) {
      const { info, samples } = decodeWav(encodeWav(renderSound(sound)));
      expect(info.peak).toBeGreaterThan(0.2);
      expect(info.peak).toBeLessThanOrEqual(0.999);
      const mean = samples.reduce((sum, value) => sum + value, 0) / samples.length;
      // A DC offset eats headroom and clicks at the loop point.
      expect(Math.abs(mean)).toBeLessThan(0.02);
    }
  });

  it('fades to silence at the end (no click on retrigger)', () => {
    for (const sound of SOUNDS) {
      if (sound.category === 'ambience') continue;
      const { samples } = decodeWav(encodeWav(renderSound(sound)));
      expect(Math.abs(samples[samples.length - 1] ?? 0)).toBeLessThan(0.02);
    }
  });

  it('stays inside the 600 kB audio budget', () => {
    expect(totalAudioBytes()).toBeLessThanOrEqual(600 * 1024);
    const encoded = SOUNDS.reduce((sum, sound) => sum + encodeWav(renderSound(sound)).byteLength, 0);
    expect(encoded).toBeLessThanOrEqual(600 * 1024);
  });

  it('matches the generated files on disk', () => {
    for (const sound of SOUNDS) {
      const path = join(PUBLIC, 'audio', sound.file);
      if (!existsSync(path)) continue; // assets are generated, not committed
      expect(readFileSync(path).byteLength).toBe(encodeWav(renderSound(sound)).byteLength);
    }
  });

  it('agrees with the manifest written by the pipeline', () => {
    expect(MANIFEST.version).toBe(2);
    expect(MANIFEST.sampleRate).toBe(SAMPLE_RATE);
    expect(MANIFEST.audio.map((entry) => entry.id).sort()).toEqual(SOUNDS.map((s) => s.id).sort());
    for (const entry of MANIFEST.audio) {
      const spec = SOUND_SPECS[entry.id as keyof typeof SOUND_SPECS];
      expect(spec, `runtime spec missing for ${entry.id}`).toBeDefined();
      expect(spec.file).toBe(entry.file);
      expect(spec.group).toBe(entry.category);
    }
  });

  it('exposes a runtime spec for every id, with sane mix values', () => {
    expect(SOUND_IDS.slice().sort()).toEqual(SOUNDS.map((sound) => sound.id).sort());
    for (const id of SOUND_IDS) {
      const spec = SOUND_SPECS[id];
      expect(spec.gain).toBeGreaterThan(0);
      expect(spec.gain).toBeLessThanOrEqual(1);
      expect(spec.retriggerMs).toBeGreaterThanOrEqual(0);
      expect(new Set(SOUND_IDS.map((key) => SOUND_SPECS[key].file)).size).toBe(SOUND_IDS.length);
    }
  });
});
